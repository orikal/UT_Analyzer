"""Models for proposed test changes awaiting user review."""

from __future__ import annotations

import itertools
from dataclasses import dataclass, field
from enum import Enum
from pathlib import Path

from .validation import ValidationResult

_id_counter = itertools.count(1)


class ApprovalState(Enum):
    PENDING = "pending"
    APPROVED = "approved"
    REJECTED = "rejected"


@dataclass
class ProposedTest:
    """A single generated unit test proposed for a file."""

    name: str
    code: str                              # code as generated by the LLM
    rationale: str = ""                    # what scenario / edge case it covers
    is_edge_case: bool = False
    approval: ApprovalState = ApprovalState.PENDING
    applied: bool = False                  # written to disk via Approved Tests tab
    applied_block: str = ""                # exact text written to disk, used to undo
    edited_code: str | None = None         # user edit, overrides ``code`` when set
    validation: ValidationResult = field(default_factory=ValidationResult)
    id: int = field(default_factory=lambda: next(_id_counter))

    @property
    def effective_code(self) -> str:
        return self.edited_code if self.edited_code is not None else self.code


@dataclass
class ProposedFileChange:
    """All proposed tests targeting one test file (existing or new)."""

    path: Path                             # absolute path of the target test file
    language: str
    is_new_file: bool = False
    original_content: str = ""             # empty for new files
    preamble: str = ""                     # imports/includes + boilerplate for new files
    tests: list[ProposedTest] = field(default_factory=list)
    source_file: Path | None = None        # the source file these tests cover
    header_path: Path | None = None        # companion header created with a new test file
    header_content: str = ""               # content for ``header_path``
    created_paths: list[Path] = field(default_factory=list)  # files this tool created on disk

    @property
    def approved_tests(self) -> list[ProposedTest]:
        return [t for t in self.tests if t.approval is ApprovalState.APPROVED]

    @property
    def rejected_tests(self) -> list[ProposedTest]:
        return [t for t in self.tests if t.approval is ApprovalState.REJECTED]

    def approve_all(self) -> None:
        for t in self.tests:
            t.approval = ApprovalState.APPROVED

    def reject_all(self) -> None:
        for t in self.tests:
            t.approval = ApprovalState.REJECTED
